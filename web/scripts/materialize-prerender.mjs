#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Every app route is prerendered at build time (see .next/prerender-manifest.json
// — no dynamicRoutes, every route has an emitted .next/server/app/<route>.html).
// Despite that, every request was still entering OpenNext's full Next server
// handler, costing 20-250ms of CPU on the Workers free plan's 10ms cap.
//
// This script runs AFTER `opennextjs-cloudflare build` and BEFORE `wrangler
// deploy`. It copies the already-built prerendered HTML into the Worker's
// static-assets directory so the custom entry (web/worker-entry.mjs) can serve
// document requests straight from `env.ASSETS` — zero Worker invocation cost —
// instead of invoking the Next handler.
//
// Emits:
//   .open-next/assets/__prerender/<route>.html   (one per prerendered route)
//   .open-next/assets/robots.txt                 (served asset-only, no Worker hit)
//   .open-next/entry-config.mjs                  (PRERENDERED routes + API_BASE,
//                                                  consumed by worker-entry.mjs)
//
// Idempotent: safe to re-run: it only overwrites files it owns.
// ---------------------------------------------------------------------------

import { existsSync, mkdirSync, copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const NEXT_DIR = join(WEB_DIR, ".next");
const MANIFEST_PATH = join(NEXT_DIR, "prerender-manifest.json");
const SERVER_APP_DIR = join(NEXT_DIR, "server", "app");
const ASSETS_DIR = join(WEB_DIR, ".open-next", "assets");
const PRERENDER_ASSETS_DIR = join(ASSETS_DIR, "__prerender");
const ENTRY_CONFIG_PATH = join(WEB_DIR, ".open-next", "entry-config.mjs");

// Routes that are prerendered but must never be served as a zero-invocation
// static hit: /_not-found has no meaningful HTML of its own, and robots.txt
// is handled separately below (plain-text asset, not HTML).
const SKIP_ROUTES = new Set(["/_not-found", "/robots.txt"]);

function fail(message) {
  console.error(`[materialize-prerender] ${message}`);
  process.exit(1);
}

if (!existsSync(MANIFEST_PATH)) {
  fail(
    `missing ${MANIFEST_PATH} — run \`opennextjs-cloudflare build\` (or \`next build\`) first.`,
  );
}
if (!existsSync(ASSETS_DIR)) {
  fail(`missing ${ASSETS_DIR} — run \`opennextjs-cloudflare build\` first.`);
}

const apiBase = process.env.NEXT_PUBLIC_API_BASE;
if (!apiBase) {
  fail(
    "NEXT_PUBLIC_API_BASE is required (the same build-time var the Next build inlines — " +
      "see scripts/deploy-web.mjs / web/env.<env>.public).",
  );
}

/** Route pathname ("/", "/runs/new", ...) -> emitted .next/server/app html file. */
function serverAppHtmlPath(route) {
  const rel = route === "/" ? "/index" : route;
  return join(SERVER_APP_DIR, `${rel}.html`);
}

/** Route pathname -> destination under .open-next/assets/__prerender/. */
function prerenderAssetPath(route) {
  const rel = route === "/" ? "/index" : route;
  return join(PRERENDER_ASSETS_DIR, `${rel}.html`);
}

const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
const routes = Object.keys(manifest.routes ?? {}).filter((route) => !SKIP_ROUTES.has(route));

if (routes.length === 0) {
  fail(`no prerendered routes found in ${MANIFEST_PATH} (routes: {})`);
}

const materialized = [];
for (const route of routes) {
  const src = serverAppHtmlPath(route);
  if (!existsSync(src)) {
    // Route is in the manifest but has no emitted HTML (e.g. an error boundary
    // route) — leave it to the Next handler rather than guessing.
    continue;
  }
  const dest = prerenderAssetPath(route);
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(src, dest);
  materialized.push(route);
}

if (materialized.length === 0) {
  fail("no route HTML files were copied — check .next/server/app output.");
}

// robots.txt is emitted as a route-handler body file, not `<route>.html`.
const robotsSrc = join(SERVER_APP_DIR, "robots.txt.body");
if (existsSync(robotsSrc)) {
  copyFileSync(robotsSrc, join(ASSETS_DIR, "robots.txt"));
} else {
  console.warn(`[materialize-prerender] no ${robotsSrc} found — skipping robots.txt asset.`);
}

const entryConfigSource = `// AUTO-GENERATED by web/scripts/materialize-prerender.mjs — do not edit by hand.
export const PRERENDERED = ${JSON.stringify(materialized, null, 2)};
export const API_BASE = ${JSON.stringify(apiBase)};
`;
writeFileSync(ENTRY_CONFIG_PATH, entryConfigSource);

console.log(
  `[materialize-prerender] wrote ${materialized.length} prerendered route(s), robots.txt, and entry-config.mjs`,
);
